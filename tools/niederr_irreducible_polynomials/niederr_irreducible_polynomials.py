# This script calculates irreducible polynomials over GF(2) using the Rabin irreducibility test over GF(2). It can
# calculate the first N irreducible polynomials, regardless of the maximum degree achieved or it can calculate all
# polynomials up to a given degree. It either prints the list of polynomials (either just as integers or together
# with the bit representation and degree) or it can emit a C++ source file using the OpenRNG specific template.
# The script enforces that each integer value calculated fits in uint32_t, which is a requirement for the intended
# use of these polynomials as default initialization values for the NIEDERREITER generator in OpenRNG.

import argparse
from dataclasses import dataclass


TEMPLATE = """
/*
 * SPDX-FileCopyrightText: <text>Copyright 2026 Arm Limited and/or its
 * affiliates <open-source-office@arm.com></text>
 *
 * SPDX-License-Identifier: MIT OR Apache-2.0 WITH LLVM-exception
 */

/*
 *
 * Default irreducible polynomials for dimensions 1 to 318
 *
 * This file is generated by niederr_irreducible_polynomials.py
 *
 */

#include <generator/niederr_default_initialization.hpp>

const uint32_t openrng::niederr_default_initialization::polynomials[openrng::niederr_default_initialization::dimen] = {{
{}
}};
"""

Poly = int
UINT32_MAX = (1 << 32) - 1


@dataclass(frozen=True)
class IrreduciblePoly:
    value: Poly
    degree: int
    binary: str


def check_u32(p: Poly, context: str = "polynomial") -> Poly:
    if p < 0 or p > UINT32_MAX:
        raise OverflowError(f"{context} does not fit in uint32_t: {p}")
    return p


def degree(p: Poly) -> int:
    """Return degree of polynomial, or -1 for zero."""
    check_u32(p)

    if p == 0:
        return -1
    return p.bit_length() - 1


def gf2_mul(a: Poly, b: Poly) -> Poly:
    """Polynomial multiplication over GF(2), without modular reduction."""
    check_u32(a, "multiplicand")
    check_u32(b, "multiplier")

    result = 0

    while b != 0:
        if b & 1:
            result ^= a
            check_u32(result, "intermediate multiplication result")

        b >>= 1

        if b != 0:
            if a & (1 << 32):
                raise OverflowError("left shift during multiplication exceeds 32 bits")
            a <<= 1
            check_u32(a, "shifted multiplicand")

    return result


def gf2_mod(dividend: Poly, divisor: Poly) -> Poly:
    """Polynomial division remainder over GF(2)."""
    check_u32(dividend, "dividend")
    check_u32(divisor, "divisor")

    if divisor == 0:
        raise ZeroDivisionError("division by zero polynomial")

    div_deg = degree(divisor)

    while degree(dividend) >= div_deg:
        shift = degree(dividend) - div_deg
        dividend ^= divisor << shift

    return dividend


def gf2_gcd(a: Poly, b: Poly) -> Poly:
    """Compute gcd of two polynomials over GF(2)."""
    check_u32(a, "gcd operand")
    check_u32(b, "gcd operand")

    while b != 0:
        r = gf2_mod(a, b)
        a = b
        b = r

    return a


def is_irreducible(f: Poly) -> bool:
    """Rabin irreducibility test over GF(2)."""
    check_u32(f, "candidate polynomial")
    n = degree(f)

    if n <= 0:
        return False

    # For degree >= 2, irreducible polynomials must have constant term 1.
    # Degree-1 polynomial x is irreducible, so it is allowed.
    if n > 1 and (f & 1) == 0:
        return False

    x = 0b10

    # Check gcd(x^(2^i) - x, f) == 1 for i = 1..floor(n/2).
    # In GF(2), subtraction is XOR.
    xp = x
    for _ in range(1, n // 2 + 1):
        xp = gf2_mod(gf2_mul(xp, xp), f)

        diff = xp ^ x
        check_u32(diff, "x^(2^i) - x")

        g = gf2_gcd(f, diff)
        if g != 1:
            return False

    # Final check: x^(2^n) == x mod f.
    xp = x
    for _ in range(n):
        xp = gf2_mod(gf2_mul(xp, xp), f)

    diff = xp ^ x
    check_u32(diff, "x^(2^n) - x")

    return gf2_mod(diff, f) == 0


def to_binary(p: Poly) -> str:
    check_u32(p, "to binary")
    return bin(p)[2:]


def first_irreducibles(dimensions: int) -> list[IrreduciblePoly]:
    """Return the first `dimensions` irreducible polynomials by increasing integer value.
       We only allow polynomials that fit in 32 bits"""
    if dimensions < 1:
        raise ValueError("dimensions must be >= 1")

    result: list[IrreduciblePoly] = []

    f = 0
    while len(result) < dimensions and f <= UINT32_MAX:
        if is_irreducible(f):
            result.append(
                IrreduciblePoly(
                    value=f,
                    degree=degree(f),
                    binary=to_binary(f),
                )
            )
        f += 1

    return result


def irreducibles_up_to_degree(maxdeg: int) -> list[IrreduciblePoly]:
    """Return all irreducible polynomials with degree <= maxdeg."""
    if maxdeg < 1:
        raise ValueError("maxdeg must be >= 1")
    if maxdeg > 31:
        raise ValueError("maxdeg must be <= 31 for uint32_t compatibility")

    result: list[IrreduciblePoly] = []

    for d in range(1, maxdeg + 1):
        start = 1 << d
        end = 1 << (d + 1)

        for f in range(start, end):
            if is_irreducible(f):
                result.append(
                    IrreduciblePoly(
                        value=f,
                        degree=d,
                        binary=to_binary(f),
                    )
                )

    return result


def print_cpp(polys: list[IrreduciblePoly]) -> None:
    body = format_cpp_polynomial_list(polys)
    print(TEMPLATE.format(body).strip())


def print_polys(polys: list[IrreduciblePoly]) -> None:
    for p in polys:
        print(f"degree={p.degree:3d}  value={p.value:12d}  0b{p.binary}")


def format_cpp_polynomial_list(polys: list[IrreduciblePoly]) -> str:
    """Format only the raw integer values for insertion into the C++ template."""
    values = []

    for p in polys:
        check_u32(p.value, "C++ polynomial value")
        values.append(str(p.value))

    # 8 values per line keeps the generated C++ readable.
    lines = []
    for i in range(0, len(values), 8):
        line = "    " + ", ".join(values[i: i + 8])
        lines.append(line)

    return ",\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Find irreducible polynomials over GF(2)."
    )

    parser.add_argument(
        "value",
        type=int,
        help=(
            "Normal mode: number of irreducible polynomials to calculate. "
            "Debug mode: maximum degree."
        ),
    )

    parser.add_argument(
        "--debug",
        action="store_true",
        help="Interpret value as maxdeg, then print all irreducibles up to that degree.",
    )

    parser.add_argument(
        "--cpp",
        action="store_true",
        help=(
            "Emit a C++ source initializer using the built-in template. "
            "The value argument is interpreted as the number of dimensions."
        ),
    )

    args = parser.parse_args()

    if args.debug and args.cpp:
        raise ValueError("--debug and --cpp cannot be used together")

    if args.debug:
        maxdeg = args.value
        polys = irreducibles_up_to_degree(maxdeg)
        print_polys(polys)

    elif args.cpp:
        dimensions = args.value
        polys = first_irreducibles(dimensions)
        print_cpp(polys)

    else:
        dimensions = args.value
        polys = first_irreducibles(dimensions)
        print_polys(polys)


if __name__ == "__main__":
    raise SystemExit(main())
