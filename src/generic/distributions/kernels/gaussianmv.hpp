#pragma once

#include <distributions/kernels/box_muller.hpp>
#include <distributions/kernels/box_muller_2.hpp>
#include <distributions/kernels/gaussian_icdf.hpp>
#include <generator/generator.hpp>
#include <openrng.h>
#include <utils/concepts.hpp>
#include <utils/cpu_features.hpp>

#include <cassert>
#include <cmath>

namespace openrng::distribution::gaussianmv {

template <CPUFeatures> struct GaussianMV {};

/**
 * Creates a multivariate Gaussian sequence using the specified method.
 *
 * The multivariate Gaussian method applies transformations on
 * the one-dimensional gaussian distribution generated by the corresponding
 * gaussian method.
 */
template <> struct GaussianMV<CPUFeatures::generic> {
  /**
   * Returns the element in the lower triangle matrix T according to the matrix
   * storage scheme.
   */
  template <typename T>
  static inline T getMatrixElement(const int64_t dimen, const int64_t mstorage,
                                   const T *t, const int64_t row,
                                   const int64_t col) {
    assert(row < dimen && col < dimen);

    switch (mstorage) {
    case VSL_MATRIX_STORAGE_PACKED:
      if (col <= row) {
        return t[col * (2 * dimen - col - 1) / 2 + row];
      }
      return 0;
    case VSL_MATRIX_STORAGE_DIAGONAL:
      if (col == row) {
        return t[row];
      }
      return 0;
    default:
      return t[row * dimen + col];
    }
  }

  template <openrng::FloatingPoint T>
  static int fill(const int64_t method, Generator *generator, const int64_t n,
                  T r[], const int64_t dimen, const int64_t mstorage,
                  const T *a, const T *t) {
    assert(n > 0);
    assert(generator != nullptr);

    switch (method) {
    case VSL_RNG_METHOD_GAUSSIANMV_BOXMULLER:
      gaussian::BoxMuller<CPUFeatures::generic>::fill<T>(generator, n * dimen,
                                                         r, 0, 1);
      break;
    case VSL_RNG_METHOD_GAUSSIANMV_BOXMULLER2:
      gaussian::BoxMuller2<CPUFeatures::generic>::fill<T>(generator, n * dimen,
                                                          r, 0, 1);
      break;
    case VSL_RNG_METHOD_GAUSSIANMV_ICDF:
      gaussian::ICDF<CPUFeatures::generic>::fill<T>(generator, n * dimen, r, 0,
                                                    1);
      break;
    default:
      return VSL_ERROR_BADARGS;
    }

    for (int64_t i = 0; i < n; i++) {

      for (int64_t j = dimen - 1; j >= 0; j--) {
        T u = 0;
        for (int64_t k = 0; k <= j; k++) {
          u += r[i * dimen + k] * getMatrixElement(dimen, mstorage, t, j, k);
        }
        r[i * dimen + j] = u + a[j];
      }
    }

    return VSL_ERROR_OK;
  }
};

} // namespace openrng::distribution::gaussianmv
